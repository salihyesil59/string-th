GAUGE_DIMENSION = 496
"""``dim G`` for either heterotic string: 480 roots plus 16 Cartan generators."""

_TOL = 1e-9


def _integer_row_basis(rows: list[list[int]]) -> list[list[int]]:
    """A basis of the lattice generated by integer row vectors, in echelon form.

    Plain integer Gaussian elimination: within each column, repeatedly reduce
    every row against the one with the smallest non-zero entry until only that
    one survives.  Exact -- Python integers throughout -- and the result is
    upper triangular on its pivot columns, so a square answer has determinant
    equal to the product of its diagonal.
    """
    matrix = [list(map(int, row)) for row in rows]
    if not matrix:
        return []
    n_cols = len(matrix[0])
    pivot = 0
    for col in range(n_cols):
        if pivot >= len(matrix):
            break
        while True:
            nonzero = [i for i in range(pivot, len(matrix)) if matrix[i][col] != 0]
            if not nonzero:
                break
            best = min(nonzero, key=lambda i: abs(matrix[i][col]))
            matrix[pivot], matrix[best] = matrix[best], matrix[pivot]
            remaining = False
            for i in range(pivot + 1, len(matrix)):
                if matrix[i][col]:
                    factor = matrix[i][col] // matrix[pivot][col]
                    matrix[i] = [
                        a - factor * b
                        for a, b in zip(matrix[i], matrix[pivot], strict=True)
                    ]
                    if matrix[i][col]:
                        remaining = True
            if not remaining:
                break
        if matrix[pivot][col] != 0:
            pivot += 1
    return matrix[:pivot]


@dataclass(frozen=True)
class RootLattice:
    """An even self-dual lattice, described by its roots and any extra generators.

    Parameters
    ----------
    name:
        Label, e.g. ``"E8 + E8"``.
    roots:
        All vectors of squared length 2, shape ``(n_roots, dim)``.
    extra:
        Generators the roots alone do not produce.  Empty for ``E_8``, whose
        root lattice is the whole thing; for ``D_{16}^{+}`` it holds the spinor
        class vector ``(1/2, ..., 1/2)``, which has norm 4 and so is not a root
        but is needed to make the lattice self-dual.
    """

    name: str
    roots: np.ndarray
    extra: np.ndarray | None = None

    def __post_init__(self) -> None:
        roots = np.asarray(self.roots, dtype=float)
        if roots.ndim != 2:
            raise ValueError(f"roots must be a 2-D array, got shape {roots.shape}")
        extra = (
            np.zeros((0, roots.shape[1]))
            if self.extra is None
            else np.asarray(self.extra, dtype=float).reshape(-1, roots.shape[1])
        )
        object.__setattr__(self, "roots", roots)
        object.__setattr__(self, "extra", extra)
        # basis() runs an exact integer elimination, which is slow enough to be
        # worth doing once per lattice; the lattice is frozen, so this is safe.
        object.__setattr__(self, "_cache", {})

    # -- shape --------------------------------------------------------------

    @property
    def dim(self) -> int:
        return int(self.roots.shape[1])

    @property
    def n_roots(self) -> int:
        return int(self.roots.shape[0])

    @property
    def generators(self) -> np.ndarray:
        """Roots and extra vectors together."""
        return np.vstack([self.roots, self.extra])

    # -- lattice properties -------------------------------------------------

    def basis(self) -> np.ndarray:
        """A basis, found by integer elimination on twice the generators.

        Coordinates lie in ``(1/2) Z``, so doubling makes everything integral;
        the basis is then halved again on the way out.
        """
        if "basis" not in self._cache:
            doubled = np.rint(2.0 * self.generators).astype(int)
            if not np.allclose(doubled / 2.0, self.generators, atol=_TOL):
                raise ValueError("generators are not half-integral")
            rows = _integer_row_basis(doubled.tolist())
            if len(rows) != self.dim:
                raise ValueError(
                    f"generators span {len(rows)} dimensions, not {self.dim}"
                )  # pragma: no cover
            self._cache["basis"] = np.array(rows, dtype=float) / 2.0
        return self._cache["basis"]

    def gram(self) -> np.ndarray:
        """Gram matrix of :meth:`basis`."""
        if "gram" not in self._cache:
            b = self.basis()
            self._cache["gram"] = b @ b.T
        return self._cache["gram"]

    def covolume(self) -> float:
        """``sqrt(det Gram)``; 1 exactly when the lattice is self-dual."""
        return float(np.sqrt(abs(np.linalg.det(self.gram()))))

    def is_integral(self) -> bool:
        """Every pairwise inner product of basis vectors is an integer."""
        gram = self.gram()
        return bool(np.all(np.abs(gram - np.rint(gram)) < 1e-8))

    def is_even(self) -> bool:
        """Every basis vector has even norm.

        For an integral lattice that is enough: expanding
        ``(sum a_i b_i)^2`` leaves even diagonal terms and twice the integer
        cross terms, so every vector is even.
        """
        diagonal = np.diag(self.gram())
        return self.is_integral() and bool(
            np.all(np.abs(diagonal - 2.0 * np.rint(diagonal / 2.0)) < 1e-8)
        )

    def is_unimodular(self) -> bool:
        """``|det Gram| = 1``, i.e. the lattice equals its dual."""
        return abs(abs(np.linalg.det(self.gram())) - 1.0) < 1e-6

    def is_even_self_dual(self) -> bool:
        """Both conditions modular invariance imposes on the internal lattice."""
        return self.is_even() and self.is_unimodular()

    def roots_have_norm_two(self) -> bool:
        """Sanity: everything called a root really has squared length 2."""
        return bool(np.allclose(np.sum(self.roots * self.roots, axis=1), 2.0))

    # -- the gauge algebra --------------------------------------------------

    @property
    def components(self) -> list[tuple[int, int]]:
        """``[(rank, n_roots), ...]`` for the irreducible pieces of the root system."""
        return decompose_roots(self.roots)

    @property
    def algebra(self) -> str:
        """The gauge algebra, named from the root geometry."""
        from ..compactification.torus import _name_from_roots

        return _name_from_roots(self.roots, self.dim)

    @property
    def algebra_candidates_from_counting(self) -> tuple[str, ...]:
        """What the rank and root count alone allow -- both heterotic algebras."""
        return identify_algebra(self.dim, self.n_roots)

    @property
    def algebra_dimension(self) -> int:
        """``roots + rank``: 496 for both heterotic lattices."""
        return self.n_roots + self.dim

    def __str__(self) -> str:  # pragma: no cover - display only
        return (
            f"{self.name:<10s} dim {self.dim}, {self.n_roots} roots, "
            f"algebra {self.algebra} of dimension {self.algebra_dimension}"
        )


