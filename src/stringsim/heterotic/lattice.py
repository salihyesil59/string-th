r"""The two sixteen-dimensional lattices, and why there are exactly two.

The heterotic string is a closed string whose two moving directions are
*different theories*: right-movers are the ten-dimensional superstring, with
central charge :math:`c_R = 15`, and left-movers are the twenty-six-dimensional
bosonic string, :math:`c_L = 26`.  Ten of the left-moving directions are
spacetime; the remaining

.. math::  26 - 10 = 16

have nowhere to go, and are compactified on a torus whose lattice
:math:`\Gamma_{16}` modular invariance forces to be **even and self-dual**:

* *even* -- every vector has even norm, so the left-moving levels stay
  half-integral in the right way;
* *self-dual* -- the lattice equals its own dual, ``covolume = 1``.

In sixteen dimensions there are exactly two such lattices, and therefore exactly
two heterotic strings:

=====================  ======  =======  ==================
lattice                roots   rank     gauge algebra
=====================  ======  =======  ==================
:math:`\Gamma_8 \oplus \Gamma_8`   480     16       ``e8 + e8``
:math:`\Gamma_{16} = D_{16}^{+}`   480     16       ``so(32)``
=====================  ======  =======  ==================

Both give ``480 + 16 = 496`` gauge bosons.  That number is *not* put in: it
comes out of the lattice, and it is separately what Green-Schwarz anomaly
cancellation demands of a ten-dimensional theory.  Two unrelated consistency
conditions landing on 496 is the reason anyone took the heterotic string
seriously.

**The two are genuinely hard to tell apart by counting.**  Rank 16 with 480
roots is ``e8 + e8`` *or* ``so(32)``, and
:func:`stringsim.compactification.torus.identify_algebra` honestly returns both.
What separates them is geometry: the ``E_8 \oplus E_8`` roots split into two
mutually orthogonal families of 240, while the ``D_{16}^{+}`` roots form one
connected system.  :func:`stringsim.compactification.torus.decompose_roots`
settles it, reusing the machinery built for the torus rather than special-casing
this.

**What is checked here and what is not.**  Evenness, integrality and
unimodularity are verified for both lattices from an explicitly constructed
basis.  That there are *only* two is a theorem of lattice theory (Niemeier's
classification in the adjacent case; in dimension 16 it is due to Witt) and is
not proved here -- what the code shows is that both candidates satisfy every
condition, and that they are inequivalent.
"""

