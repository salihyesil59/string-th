def _d_roots(dim: int) -> np.ndarray:
    r"""``+/- e_i +/- e_j`` for ``i < j``: the ``D_n`` roots, ``2n(n-1)`` of them."""
    out = []
    for i, j in itertools.combinations(range(dim), 2):
        for sign_i in (1.0, -1.0):
            for sign_j in (1.0, -1.0):
                vector = np.zeros(dim)
                vector[i] = sign_i
                vector[j] = sign_j
                out.append(vector)
    return np.array(out)


def _spinor_class(dim: int, even_minus_signs: bool = True) -> np.ndarray:
    r"""Vectors ``(+/-1/2, ..., +/-1/2)`` with an even number of minus signs."""
    out = []
    for signs in itertools.product((0.5, -0.5), repeat=dim):
        negatives = sum(1 for s in signs if s < 0)
        if (negatives % 2 == 0) == even_minus_signs:
            out.append(np.array(signs))
    return np.array(out)


def e8() -> RootLattice:
    r"""The :math:`E_8` lattice: 240 roots, even, self-dual, dimension 8.

    Constructed as the union of the :math:`D_8` roots (112 of them) and the
    even half-integer vectors (128), which is the standard description
    :math:`E_8 = D_8 \cup (D_8 + s)` restricted to norm 2.  Its root lattice is
    the whole lattice, so no extra generator is needed.
    """
    roots = np.vstack([_d_roots(8), _spinor_class(8)])
    return RootLattice("E8", roots)


def e8_squared() -> RootLattice:
    r""":math:`E_8 \oplus E_8`: two orthogonal copies, 480 roots in 16 dimensions."""
    single = e8().roots
    zeros = np.zeros((len(single), 8))
    roots = np.vstack(
        [np.hstack([single, zeros]), np.hstack([zeros, single])]
    )
    return RootLattice("E8 + E8", roots)


def d16_plus() -> RootLattice:
    r""":math:`D_{16}^{+}`: the ``D_16`` root lattice plus one spinor class.

    The 480 roots are the ``D_16`` ones; the spinor vectors
    :math:`(\pm\tfrac12)^{16}` have norm 4, so they are *not* roots, but one of
    them must be included as a generator or the lattice is not self-dual --
    ``D_16`` alone has covolume 2.  That extra coset is what turns ``so(32)``'s
    root lattice into an even self-dual one, and it is why the gauge group is
    ``Spin(32)/Z_2`` rather than ``SO(32)``.
    """
    roots = _d_roots(16)
    spinor = np.full((1, 16), 0.5)
    return RootLattice("D16+", roots, spinor)


def heterotic_lattices() -> dict[str, RootLattice]:
    """The two even self-dual sixteen-dimensional lattices, by name."""
    return {"E8 + E8": e8_squared(), "Spin(32)/Z2": d16_plus()}


def even_self_dual_dimension_rule(dim: int) -> bool:
    r"""Whether a positive-definite even self-dual lattice can exist in ``dim``.

    They exist only when ``dim`` is a multiple of 8 -- a theorem, stated here
    rather than proved.  It is the reason 16 works: the heterotic string needs
    exactly ``26 - 10 = 16`` internal left-moving directions, and 16 happens to
    be a permitted dimension.  Had the two critical dimensions differed by
    anything else, there would be no heterotic string.
    """
    if dim < 0:
        raise ValueError("dimension must be non-negative")
    return dim % 8 == 0
